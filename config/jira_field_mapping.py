PRIORITY_TO_SEVERITY = {
    "Critical": "Highest",
    "High": "High",
    "Medium": "Medium",
    "Low": "Low",
    "Trivial": "Lowest",
}


# ──────────────────────────────────────────────────────────────
# Discovered Field Loader
# ──────────────────────────────────────────────────────────────

def load_discovered_fields() -> dict:
    """Load discovered field mappings from JSON if available."""
    if MAPPING_JSON.exists():
        with open(MAPPING_JSON, "r", encoding="utf-8") as f:
            return json.load(f)
    return {}


def get_required_field_ids(issue_type: str = "Bug") -> dict[str, str]:
    """Get a dict of {field_name: field_id} for required fields of an issue type.

    Returns from discovered JSON if available, otherwise returns empty dict.
    """
    discovered = load_discovered_fields()
    it_data = discovered.get("issue_types", {}).get(issue_type, {})
    fields = it_data.get("fields", {})
    return {
        v["name"]: k
        for k, v in fields.items()
        if v.get("required")
    }


def get_field_allowed_values(issue_type: str, field_id: str) -> list[dict]:
    """Get allowed values for a select field from discovered data."""
    discovered = load_discovered_fields()
    it_data = discovered.get("issue_types", {}).get(issue_type, {})
    field_info = it_data.get("fields", {}).get(field_id, {})
    return field_info.get("allowed_values", [])


# ──────────────────────────────────────────────────────────────
# QA Touch -> Jira Mapper
# ──────────────────────────────────────────────────────────────

class QATouchToJiraMapper:
    """Maps QA Touch test case data to Jira issue fields.

    Uses discovered field IDs from config/jira_field_mapping.json when available.
    Falls back gracefully when field IDs are unknown.
    """

    def __init__(self):
        self._discovered = load_discovered_fields()
        self._required_fields_cache: dict[str, dict] = {}

    def _get_required_fields(self, issue_type: str) -> dict[str, str]:
        """Get {field_name: field_id} for required fields, with caching."""
        if issue_type not in self._required_fields_cache:
            self._required_fields_cache[issue_type] = get_required_field_ids(issue_type)
        return self._required_fields_cache[issue_type]

    def _find_field_id(self, issue_type: str, field_name_pattern: str) -> Optional[str]:
        """Find a field ID by matching against the field name (case-insensitive partial match)."""
        required = self._get_required_fields(issue_type)
        pattern_lower = field_name_pattern.lower()
        for name, fid in required.items():
            if pattern_lower in name.lower():
                return fid
        # Also search all fields (not just required)
        it_data = self._discovered.get("issue_types", {}).get(issue_type, {})
        for fid, finfo in it_data.get("fields", {}).items():
            if pattern_lower in finfo.get("name", "").lower():
                return fid
        return None

    def _match_allowed_value(self, issue_type: str, field_id: str, search_value: str) -> Optional[dict]:
        """Find the best matching allowed value for a select field."""
        allowed = get_field_allowed_values(issue_type, field_id)
        if not allowed:
            return None

        search_lower = search_value.lower().strip()

        # Exact match first
        for av in allowed:
            val = av.get("value") or av.get("name") or ""
            if val.lower() == search_lower:
                return av

        # Partial match
        for av in allowed:
            val = av.get("value") or av.get("name") or ""
            if search_lower in val.lower() or val.lower() in search_lower:
                return av

        # Return first value as fallback
        return allowed[0] if allowed else None

    def map_bug_fields(
        self,
        module: str = "",
        steps: str = "",
        expected: str = "",
        actual: str = "",
        environment: str = "QA",
        severity: str = "Medium",
        build: str = "",
        title: str = "",
        test_case_id: str = "",
    ) -> dict[str, Any]:
        """Map QA Touch test case data to Jira Bug fields.

        Returns a dict of {field_id: value} suitable for passing to
        jira.create_issue(fields={...}).

        Only includes fields where we have both a known field_id and a value.
        """
        mapped = {}
        issue_type = "Bug"

        # Module
        fid = self._find_field_id(issue_type, "module")
        if fid and module:
            av = self._match_allowed_value(issue_type, fid, module)
            if av:
                if "id" in av:
                    mapped[fid] = {"id": av["id"]}
                elif "value" in av:
                    mapped[fid] = {"value": av["value"]}

        # Steps to Reproduce
        fid = self._find_field_id(issue_type, "steps to reproduce")
        if fid and steps:
            mapped[fid] = steps

        # Bug Overview
        fid = self._find_field_id(issue_type, "bug overview")
        if fid:
            overview = title or "Bug found during QA testing"
            if test_case_id:
                overview = f"[{test_case_id}] {overview}"
            mapped[fid] = overview

        # Expected Behavior
        fid = self._find_field_id(issue_type, "expected")
        if fid and expected:
            mapped[fid] = expected

        # Actual Behavior
        fid = self._find_field_id(issue_type, "actual")
        if fid and actual:
            mapped[fid] = actual

        # Environment Found
        fid = self._find_field_id(issue_type, "environment")
        if fid and environment:
            av = self._match_allowed_value(issue_type, fid, environment)
            if av:
                if "id" in av:
                    mapped[fid] = {"id": av["id"]}
                elif "value" in av:
                    mapped[fid] = {"value": av["value"]}

        # Severity
        fid = self._find_field_id(issue_type, "severity")
        if fid and severity:
            # Map from QA Touch priority names to Jira severity
            jira_severity = PRIORITY_TO_SEVERITY.get(severity, severity)
            av = self._match_allowed_value(issue_type, fid, jira_severity)
            if av:
                if "id" in av:
                    mapped[fid] = {"id": av["id"]}
                elif "value" in av:
                    mapped[fid] = {"value": av["value"]}

        # Affected Build Number
        fid = self._find_field_id(issue_type, "affected build") or self._find_field_id(issue_type, "build number")
        if fid and build:
            mapped[fid] = build

        return mapped

    def get_unmapped_required_fields(self, issue_type: str, mapped_fields: dict) -> list[str]:
        """Return names of required fields that were NOT populated in mapped_fields.

        Useful for alerting testers about fields they need to fill manually.
        """
        required = self._get_required_fields(issue_type)
        unmapped = []
        for name, fid in required.items():
            # Skip standard fields that are always set
            if fid in ("project", "issuetype", "summary", "description"):
                continue
            if fid not in mapped_fields:
                unmapped.append(f"{name} ({fid})")
        return unmapped


# Module-level singleton
mapper = QATouchToJiraMapper()
