"""
Jira Field Mapping Configuration for NexaiQ-Core (NC) Project.

This module provides:
- Field ID constants for NC custom fields
- QA Touch -> Jira status mapping
- QATouchToJiraMapper class for mapping test case data to Jira fields

Field IDs are loaded from config/jira_field_mapping.json if available
(generated by tools/discover_jira_fields.py). Otherwise, falls back to
the known field IDs documented in the NC Jira configuration report.

Usage:
    from config.jira_field_mapping import mapper, QA_TOUCH_TO_JIRA_STATUS

    # Map QA Touch test data to Jira Bug fields
    jira_fields = mapper.map_bug_fields(
        module="Views",
        steps="1. Login\\n2. Navigate to Views",
        expected="Camera feed loads",
        actual="Feed shows black screen",
        environment="QA",
        severity="High",
        build="v1.50.0"
    )
"""
